def gua_info(bin6: str) -> dict:
    """根据 6 位二进制返回卦象完整信息。"""
    name = GUA_NAME_BY_BIN[bin6]
    idx = GUA_INDEX[name]
    gong, seq = idx["gong"], idx["seq"]
    shi, ying = SHI_YING[seq]
    lower_bin, upper_bin = bin6[0:3], bin6[3:6]
    return {
        "bin": bin6,
        "name": name,
        "gong": gong,
        "gong_wuxing": GONG_WUXING[gong],
        "seq": seq,
        "seq_name": SHI_YING_NAME[seq],
        "shi": shi,
        "ying": ying,
        "lower": BAGUA_BY_BIN[lower_bin],
        "upper": BAGUA_BY_BIN[upper_bin],
        "body": gua_body(bin6)["body"],
        "order_wenwang": GUA_ORDER_WENWANG.get(bin6),
    }


def najia_of(lower: str, upper: str):
    """返回六个爻位的纳甲（初→上）。

    纳甲取**上下经卦**，不是卦宫：
        下卦用该经卦的内三爻纳甲，上卦用该经卦的外三爻纳甲。
    乾坤两卦内外天干不同（乾内甲外壬、坤内乙外癸），其余六卦内外同干。
    例：天水讼（下坎上乾）→ 戊寅 戊辰 戊午 壬午 壬申 壬戌。
    """
    gan_in, _, zhi_in, _ = NAJIA[lower]
    gan_out = NAJIA[upper][1]
    zhi_out = NAJIA[upper][3]
    return [(gan_in, z) for z in zhi_in] + [(gan_out, z) for z in zhi_out]


def gua_body(bin6: str) -> dict:
    """判卦体：六冲卦 / 六合卦。

    不看卦名硬编码，直接用该卦六爻纳甲验证：
    初四、二五、三上三对爻若全部相冲 → 六冲卦；全部相合 → 六合卦。
    """
    lower = BAGUA_BY_BIN[bin6[0:3]]
    upper = BAGUA_BY_BIN[bin6[3:6]]
    zhis = NAJIA[lower][2] + NAJIA[upper][3]
    chong = all(ZHI_CHONG[zhis[i]] == zhis[i + 3] for i in range(3))
    he = all(ZHI_LIUHE[zhis[i]] == zhis[i + 3] for i in range(3))
    body = "六冲" if chong else ("六合" if he else "常卦")
    return {"body": body, "zhis": zhis,
            "pairs": [f"{zhis[i]}—{zhis[i+3]}" for i in range(3)]}


