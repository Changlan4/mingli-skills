LIUQIN_ORDER = ["父母", "兄弟", "子孙", "妻财", "官鬼"]


def liuqin(gong: str, zhi: str) -> str:
    """以卦宫五行为我，求该爻地支对应的六亲。"""
    me = GONG_WUXING[gong]
    other = ZHI_WUXING[zhi]
    if other == me:
        return "兄弟"
    if SHENG[other] == me:
        return "父母"      # 生我者
    if SHENG[me] == other:
        return "子孙"      # 我生者
    if KE[other] == me:
        return "官鬼"      # 克我者
    if KE[me] == other:
        return "妻财"      # 我克者
    return "?"


